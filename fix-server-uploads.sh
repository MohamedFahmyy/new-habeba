#!/usr/bin/env bash
# ==============================================================================
# HABEBA PLATFORM – Configure & Fix Server Upload Permissions & Nginx Body Limits
# Allows users to upload photos up to 25MB smoothly on Linux / VPS
# ==============================================================================

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

APP_DIR="/var/www/habeba"
PM2_APP_NAME="habeba-8282"

echo -e "\n${CYAN}=================================================================${NC}"
echo -e "${GREEN}     📸 HABEBA PLATFORM – Enabling & Fixing Server Uploads       ${NC}"
echo -e "${CYAN}=================================================================${NC}\n"

# 1. Root Check
if [ "$EUID" -ne 0 ]; then
  echo -e "${RED}[ERROR] Please run this script with sudo or as root:${NC}"
  echo -e "Usage: sudo bash fix-server-uploads.sh"
  exit 1
fi

cd "$APP_DIR" 2>/dev/null || cd "$(dirname "$0")"
APP_DIR="$(pwd)"

echo -e "${YELLOW}[1/5] Creating and verifying storage directories...${NC}"
mkdir -p "${APP_DIR}/storage"
mkdir -p "${APP_DIR}/storage/uploads"
mkdir -p "${APP_DIR}/storage/uploads/receipts"
mkdir -p "${APP_DIR}/server/storage/uploads" 2>/dev/null || true

# 2. Set Full Read/Write Permissions (777) so Node/PM2 can write freely
echo -e "${YELLOW}[2/5] Setting full 777 write permissions on storage...${NC}"
chmod -R 777 "${APP_DIR}/storage"
chmod -R 777 "${APP_DIR}/storage/uploads"
chmod -R 777 "${APP_DIR}/storage/uploads/receipts"
chmod -R 777 "${APP_DIR}/server/storage" 2>/dev/null || true

# Set ownership to current user or www-data if available
if id "www-data" &>/dev/null; then
  chown -R www-data:www-data "${APP_DIR}/storage" 2>/dev/null || true
  chmod -R 777 "${APP_DIR}/storage"
fi
echo -e "${GREEN}✓ Storage permissions configured (777 write access granted).${NC}"

# 3. Configure Nginx Upload Limit (client_max_body_size)
echo -e "\n${YELLOW}[3/5] Configuring Nginx client_max_body_size to 50M...${NC}"
if command -v nginx &>/dev/null; then
  # Add global config in /etc/nginx/conf.d if directory exists
  if [ -d "/etc/nginx/conf.d" ]; then
    cat > /etc/nginx/conf.d/habeba_uploads.conf << 'EOF'
# Generated by Habeba Platform setup
client_max_body_size 50M;
EOF
    echo -e "${GREEN}✓ Created /etc/nginx/conf.d/habeba_uploads.conf (50M upload limit).${NC}"
  fi

  # Also ensure client_max_body_size is in /etc/nginx/nginx.conf http block if not present
  if [ -f "/etc/nginx/nginx.conf" ] && ! grep -q "client_max_body_size" /etc/nginx/nginx.conf; then
    sed -i '/http {/a \    client_max_body_size 50M;' /etc/nginx/nginx.conf
    echo -e "${GREEN}✓ Added client_max_body_size 50M to /etc/nginx/nginx.conf.${NC}"
  fi

  # Check if site configurations exist and update them
  if [ -d "/etc/nginx/sites-available" ]; then
    for conf in /etc/nginx/sites-available/*; do
      if [ -f "$conf" ] && ! grep -q "client_max_body_size" "$conf"; then
        sed -i '/server {/a \    client_max_body_size 50M;' "$conf" 2>/dev/null || true
      fi
    done
  fi

  # Test Nginx syntax and reload
  if nginx -t &>/dev/null; then
    systemctl reload nginx 2>/dev/null || service nginx reload 2>/dev/null || true
    echo -e "${GREEN}✓ Nginx reloaded successfully with 50M body size limit.${NC}"
  else
    echo -e "${YELLOW}! Nginx syntax test note: check your custom nginx configs.${NC}"
  fi
else
  echo -e "${CYAN}Note: Standalone Node.js server (Nginx not running). Port 8282 directly handles uploads.${NC}"
fi

# 4. Update .env with explicit upload directory and size limit
echo -e "\n${YELLOW}[4/5] Updating .env configuration...${NC}"
ENV_FILE="${APP_DIR}/.env"
if [ -f "$ENV_FILE" ]; then
  # Remove old keys if present
  sed -i '/MAX_FILE_SIZE_BYTES/d' "$ENV_FILE" 2>/dev/null || true
  sed -i '/UPLOAD_DIR/d' "$ENV_FILE" 2>/dev/null || true

  # Append correct upload settings
  echo "MAX_FILE_SIZE_BYTES=26214400" >> "$ENV_FILE"
  echo "UPLOAD_DIR=${APP_DIR}/storage/uploads" >> "$ENV_FILE"
  echo -e "${GREEN}✓ .env updated: MAX_FILE_SIZE_BYTES=25MB & UPLOAD_DIR=${APP_DIR}/storage/uploads.${NC}"
fi

# 5. Reload PM2 Process with new environment
echo -e "\n${YELLOW}[5/5] Reloading PM2 process (${PM2_APP_NAME})...${NC}"
if command -v pm2 &>/dev/null; then
  pm2 reload "$PM2_APP_NAME" --update-env 2>/dev/null || pm2 restart "$PM2_APP_NAME" --update-env 2>/dev/null || true
  pm2 save >/dev/null 2>&1 || true
  echo -e "${GREEN}✓ PM2 process reloaded with updated environment.${NC}"
fi

# Verification test: create and delete a temporary file
TEST_FILE="${APP_DIR}/storage/uploads/.write_test"
if touch "$TEST_FILE" 2>/dev/null; then
  rm -f "$TEST_FILE"
  echo -e "\n${GREEN}=================================================================${NC}"
  echo -e "${GREEN}🎉 SERVER IS FULLY CONFIGURED FOR PHOTO UPLOADS!${NC}"
  echo -e "${GREEN}=================================================================${NC}"
  echo -e "📁 Upload Directory:  ${CYAN}${APP_DIR}/storage/uploads${NC}"
  echo -e "⚖️ Max File Size:     ${CYAN}25 MB${NC}"
  echo -e "🚀 Permissions:       ${CYAN}777 (Full read/write)${NC}"
  echo -e "${GREEN}=================================================================${NC}\n"
else
  echo -e "${RED}[WARNING] Test write failed. Please check permissions manually.${NC}"
fi
